"""Full physical gates on saved, real Clarabel fields, including a rejection.

The compressed fixture contains two unpolished solver fields on the same
1481-element P06A mesh. It is not generated by the recovery under test.
"""
import json
from pathlib import Path
import unittest
import accuracy_driver as driver
import experiment_core as core
from experiment_core import np
from test_inverse_dual_guide import physical_triangle


FIXTURE=Path(__file__).parent/'fixtures/lower_polish_actual1481.npz'


class PrimalRowRecoveryTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        _,record=driver.load_model('P06A')
        with np.load(FIXTURE) as data:
            cls.mesh=core.mesh_from_arrays(data['xy'],data['tri'],data['material_id'],record)
            if cls.mesh.mesh_id!=str(data['mesh_id']):
                raise ValueError('Saved actual mesh identity changed')
            if cls.mesh.physical_model_id!=str(data['physical_model_id']):
                raise ValueError('Saved actual physical model identity changed')
            if int(data['q'])!=8 or str(data['case'])!='P06A':
                raise ValueError('Unexpected actual solver-field fixture')
            cls.fields={key:data[key].copy() for key in ['equilibrium_failure','yield_failure']}
            cls.fs={key:float(data[key+'_fs']) for key in ['equilibrium','yield']}
            cls.provenance=json.loads(str(data['provenance']))

    def test_actual_equilibrium_failure_passes_original_physics_in_first_stage(self):
        prepared=core.Prepared(self.mesh,self.fs['equilibrium'],'lower',8)
        source=self.fields['equilibrium_failure'].copy()
        unchanged=source.copy()
        before=core.evaluate(prepared,source)
        self.assertFalse(before['physical_pass'])
        self.assertFalse(before['witness'])
        self.assertGreater(before['raw_lower_errors']['equilibrium'],core.RAW_STRESS_TOL)
        self.assertEqual(before['raw_lower_errors']['yield'],0.)
        record,result,field=core.polish_primal(prepared,source)
        np.testing.assert_array_equal(source,unchanged)
        self.assertTrue(record['accepted'])
        self.assertTrue(record['weighted_lower_recovery']['accepted'])
        self.assertEqual(record['weighted_lower_recovery']['stages'][0]['cumulative_budget'],100)
        self.assertEqual(len(record['weighted_lower_recovery']['stages']),1)
        self.assertLessEqual(record['iterations'],100)
        self.assertNotIn('fallback_from_unchanged_source',record)
        self.assertTrue(result['physical_pass'])
        self.assertTrue(result['witness'])
        independent=core.evaluate(prepared,field)
        self.assertEqual(result,independent)
        self.assertLess(independent['raw_lower_errors']['equilibrium'],core.RAW_STRESS_TOL)
        self.assertLess(independent['raw_lower_errors']['yield'],core.RAW_STRESS_TOL)
        self.assertGreaterEqual(independent['value'],core.LOWER_TARGET)

    def test_actual_yield_failure_uses_legacy_fallback_and_retains_original_field(self):
        prepared=core.Prepared(self.mesh,self.fs['yield'],'lower',8)
        source=self.fields['yield_failure'].copy()
        unchanged=source.copy()
        before=core.evaluate(prepared,source)
        self.assertFalse(before['physical_pass'])
        self.assertGreater(before['raw_lower_errors']['yield'],core.RAW_STRESS_TOL)
        record,result,field=core.polish_primal(prepared,source)
        weighted=record['weighted_lower_recovery']
        self.assertTrue(weighted['attempted'])
        self.assertFalse(weighted['accepted'])
        self.assertTrue(weighted['stages'])
        self.assertTrue(all(not stage['physical_pass'] for stage in weighted['stages']))
        # Equality accuracy alone must not admit a field violating yield.
        self.assertLess(weighted['stages'][0]['raw_lower_errors']['equilibrium'],core.RAW_STRESS_TOL)
        self.assertGreater(weighted['stages'][0]['raw_lower_errors']['yield'],core.RAW_STRESS_TOL)
        self.assertTrue(record['fallback_from_unchanged_source'])
        self.assertEqual(record['method'],'original_equality_lsmr_then_full_physical_audit')
        self.assertFalse(record['accepted'])
        self.assertGreater(record['after_raw']['yield'],core.RAW_STRESS_TOL)
        self.assertFalse(result['physical_pass'])
        self.assertFalse(result['witness'])
        self.assertEqual(result,before)
        np.testing.assert_array_equal(source,unchanged)
        np.testing.assert_array_equal(field,unchanged)

    def test_upper_retains_exact_previous_unweighted_recovery(self):
        prepared=core.Prepared(physical_triangle(),.5,'upper',8)
        source=np.zeros(prepared.original[0].shape[1])
        before=core.evaluate(prepared,source)
        self.assertFalse(before['physical_pass'])
        E,b,*_=prepared.original
        legacy=core.lsmr(E,b-E@source,atol=1e-15,btol=1e-15,maxiter=10000)
        legacy_field=source+legacy[0]
        legacy_result=core.evaluate(prepared,legacy_field)
        record,result,field=core.polish_primal(prepared,source)
        self.assertIsNone(prepared.original_row_norm)
        self.assertNotIn('weighted_lower_recovery',record)
        self.assertEqual(record['iterations'],legacy[2])
        self.assertEqual(record['lsmr_flag'],legacy[1])
        expected_field=legacy_field if legacy_result['physical_pass'] else source
        expected_result=legacy_result if legacy_result['physical_pass'] else before
        np.testing.assert_array_equal(field,expected_field)
        self.assertEqual(result,expected_result)
        np.testing.assert_array_equal(source,np.zeros(len(source)))


if __name__=='__main__':unittest.main()
